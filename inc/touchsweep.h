/* 竖向扫描诊断，2026-11-20。本页的存在理由见上。
 *
 * 画板页曾留下两条完美的水平线，外加一段完全没有反应的屏幕区域。这是同一个
 * 故障被看到两次：要么面板在那一段不再上报采样，要么它整条带只报同一个 Y 值。
 * 像素坐标分不清这两种情况，因此本页按每 20 像素一条带，统计有多少采样落进来、
 * 这些采样携带的原始值范围有多大。空带与原始值范围只有一个数的带是两种不同
 * 的故障，读数会明确告诉你是哪一种。
 *
 * 这里什么都不写：不写标定文件、不写页面状态、不作画。
 */
#ifndef TERMINAL_TOUCHSWEEP_H
#define TERMINAL_TOUCHSWEEP_H
#include "terminal.h"

/* 扫描期间用本函数替代 app_event：它不得导航，也不得画笔画线。 */
void touch_sweep_event(App *app, Event event);
/* 重绘整帧：标尺、每带采样数，以及实时的原始值对。 */
void touch_sweep_draw(App *app);
#endif
